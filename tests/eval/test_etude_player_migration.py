FIXTURE = Path(__file__).parents[1] / "fixtures/etude_sdk_025"
# The eval run that played on 0.2.5, before card data moved the live run to
# `elemental.RUN`; the fixture retains it under this name.
ELEMENTAL_RUN = "mtg183-eval"


def _elemental_state() -> elemental.EvalState:
    return elemental.EvalState(
        checkpoints={
            update: elemental.Checkpoint(
                updates=update,
                run="migration-fixture",
                artifact=ArtifactRef(
                    uri=f"file:///fixture/u{update:06d}.pt",
                    sha256=str(index + 1) * 64,
                    size_bytes=10,
                ),
                coordinates={"updates": update},
            )
            for index, update in enumerate((0, 50))
        },
    )


def _card_pairing() -> Pairing:
    return Pairing(
        name="endpoint",
        **{
            name: Checkpoint(
                trial=name,
                seed=index + 1,
                job="migration-fixture",
                updates=200,
                sha256=str(index + 1) * 64,
                size_bytes=10,
                key=f"fixtures/{name}.pt",
            )
            for index, name in enumerate(("mtg186", "mtg181"))
        },
    )


def _scheduled(case: str) -> tuple[str, str, list[Match]]:
    if case == "elemental":
        return (
            elemental.EXPERIMENT,
            ELEMENTAL_RUN,
            [unit.matches[0] for unit in elemental.units(_elemental_state())],
        )
    if case == "cards":
        return cards.EXPERIMENT, cards.RUN, cards.matches(_card_pairing())[:1]
    manifest = _manifest()
    manifest.protocol = MonitorProtocol(
        deal_seeds=(101, 102), opponent="heuristic", include_mirrors=True
    )
    definition = benchmark.benchmark(manifest)
    checkpoint = CheckpointRef(
        key=CheckpointKey(run="migration-fixture", name="u000050"),
        artifact=ArtifactRef(
            uri="file:///fixture/u000050.pt", sha256="2" * 64, size_bytes=10
        ),
    )
    return (
        definition.name,
        "benchmark-fixture",
        definition.matchups[0].matches(checkpoint),
    )


def _never_play(match: Match) -> Tables:
    pytest.fail(f"retained match was scheduled again: {match.key}")


def _retained_bytes(directory: Path) -> dict[str, bytes]:
    return {
        str(path.relative_to(directory)): path.read_bytes()
        for folder in ("matches", "tables")
        for path in (directory / folder).glob("*")
        if path.is_file()
    }


@pytest.mark.parametrize("case", ["elemental", "cards", "benchmark"])
def test_025_resume_preserves_keys_scores_and_native_seats(
    case: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    experiment, run, matches = _scheduled(case)
    store = tmp_path / "store"
    shutil.copytree(FIXTURE / case, store)
    root = store / run
    retained = _retained_bytes(root)
    convert(run, store)
    keys = {path.stem for path in (root / "matches").glob("*.json")}
    assert {match.key for match in matches} == keys
    environment = Environment.model_validate_json(
        (root / "environment.json").read_bytes()
    )
    result = evaluate(
        experiment=experiment,
        run=run,
        environment=environment,
        matches=matches,
        play=_never_play,
        directory=store,
    )
    assert result.played == 0
    assert result.skipped == len(keys)
    assert _retained_bytes(root) == retained
    table = "plays" if case == "benchmark" else "games"
    with statsdb(experiment, store) as db:
        # Opposite native assignments must still join to the same participant.
        native_seat = (
            "case when g.on_play then 0 else 1 end"
            if case == "benchmark"
            else "g.game_seat"
        )
        grouped = db.execute(
            f"select p.name, g.seat, {native_seat} as game_seat, count(*), avg(g.score) from {table} g"
            " join seats s using (run, match, seat)"
            " join players p on p.player = s.player group by all"
        ).fetchall()
        assert sum(count for _, _, _, count, _ in grouped) == sum(
            m.games for m in matches
        ) * (1 if case == "cards" else 2)
        assert {game_seat for _, _, game_seat, _, _ in grouped} == {0, 1}
        for name, seat, game_seat, count, score in grouped:
            assert count > 0
            assert score == float(1 - seat)
            assert name in {match.players[seat].name for match in matches}
        if case == "cards":
            # The collector validates the entire retained deal's four deck/seat legs.
            deals = cards.Conditions.model_validate(matches[0].conditions).deals
            monkeypatch.setattr(cards, "deals", lambda: deals)
            summary = cards.summary(db)
            assert summary.games == len(deals) * 4
            for side in (summary.mtg186_on_ur, summary.mtg186_on_gw):
                assert side.play.score == 1.0
                assert side.draw.score == 1.0
                assert side.play.valid == side.draw.valid == len(deals)
    if case == "elemental":
        # Anchor admission compares against the source that produced this fixture,
        # independently of future edits to the live heuristic's implementation.
        sources = {
            participant.version.source
            for path in (root / "matches").glob("*.json")
            for participant in MatchRecord.model_validate_json(
                path.read_bytes()
            ).match.players
            if participant.name == "heuristic"
        }
        (source,) = sources
        assert source is not None
        heuristic = Code.model_validate(
            {"name": "heuristic", "version": {"source": source}}
        )
        monkeypatch.setattr(report, "heuristic_code", lambda: heuristic)
        monkeypatch.setattr(report, "RUN", ELEMENTAL_RUN)
        (tmp_path / "state.json").write_text(_elemental_state().model_dump_json())
        results = load(tmp_path, store)
        assert set(results.heuristic) == {0, 50}
        assert set(results.pairs) == {(50, 0)}
        rating = fit_rows(results)
        assert {row["player_a_seat"] for row in rating} == {0, 1}
        assert all(row["score_a"] == 1.0 for row in rating)


def test_report_keeps_digest_keyed_02_heuristic_anchor(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The SDK's old code identity has no display name or per-match source."""
    source = "f" * 64
    heuristic = Code.model_validate(
        {"name": "heuristic", "version": {"source": source}}
    )
    monkeypatch.setattr(report, "heuristic_code", lambda: heuristic)
    state = _elemental_state()
    (tmp_path / "state.json").write_text(state.model_dump_json())
    model = elemental.checkpoint_model(state.checkpoints[0])
    matches = [
        Match.model_validate(
            {
                "players": [
                    model.model_dump(mode="json"),
                    {
                        "name": "heuristic",
                        "kind": "code",
                        "artifact": digest,
                        "config": {},
                    },
                ],
                "conditions": {"kind": "subset"},
                "games": 2,
            }
        )
        for digest in (source, "e" * 64)
    ]

    def play(match: Match) -> Tables:
        return {
            "games": elemental.game_rows(
                [
                    GameRow(
                        model_deck="elemental_ur",
                        heuristic_deck="elemental_gw",
                        model_seat=seat,
                        deal=seat,
                        score=1.0,
                        valid=True,
                        terminated=True,
                        truncated=False,
                        failure=None,
                        decisions=1,
                        model_decisions=1,
                        seconds=0.01,
                    )
                    for seat in (0, 1)
                ],
                "subset",
            )
        }

    evaluate(
        experiment=elemental.EXPERIMENT,
        run=elemental.RUN,
        environment=Environment(name="legacy-anchor", files="a" * 64),
        matches=matches,
        play=play,
        directory=tmp_path / "store",
    )
    results = load(tmp_path, tmp_path / "store")
    # The unrecognized older source must be excluded, not merged or rated.
    assert [(row.model_seat, row.score) for row in results.heuristic[0]] == [
        (0, 1.0),
        (1, 1.0),
    ]
    assert results.pairs == {}


def test_historical_and_current_game_columns_union_without_losing_seats(
    tmp_path: Path,
) -> None:
    experiment, run, matches = _scheduled("cards")
    store = tmp_path / "store"
    shutil.copytree(FIXTURE / "cards", store)
    root = store / run
    retained = _retained_bytes(root)
    convert(run, store)
    # A new synthetic deal follows the retained match; its producer uses the new schema.
    extra = matches[0].model_copy(update={"conditions": {"deals": [99]}, "games": 4})

    def play(match: Match) -> Tables:
        assert match == extra
        rows = [
            row.model_copy(update={"score": 1.0, "valid": True, "failure": None})
            for row in cards._invalid((99,), "fixture")
        ]
        return {"games": cards.game_rows(rows)}

    environment = Environment.model_validate_json(
        (root / "environment.json").read_bytes()
    )
    result = evaluate(
        experiment=experiment,
        run=run,
        environment=environment,
        matches=[*matches, extra],
        play=play,
        directory=store,
    )
    assert (result.played, result.skipped) == (1, len(matches))
    with statsdb(experiment, store) as db:
        assert db.execute(
            "select distinct seat, game_seat from games order by all"
        ).fetchall() == [(0, 0), (0, 1)]
        assert db.execute("select count(*) from games").fetchone() == (
            matches[0].games + 4,
        )
    # Newly appended files may be compacted, but every retained match record stays exact.
    assert {
        name: (root / name).read_bytes()
        for name in retained
        if name.startswith("matches/")
    } == {name: body for name, body in retained.items() if name.startswith("matches/")}
