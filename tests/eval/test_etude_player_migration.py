"""Real 0.2.5 benchmark records keep their keys, attribution and game seats under the current SDK.

The fixture holds synthetic scalar outcomes for the training benchmark's
schedule; resuming it must never invoke game execution. Its files are not
regenerated by tests. Etude reads per-file runs only once converted to blocks
(`etude convert-eval`), which writes beside the retained files and never
changes them.
"""

from pathlib import Path
import shutil

from etude.checkpoints import CheckpointRef
from etude.eval.convert import convert
from etude.eval.query import statsdb
from etude.eval.records import Environment, Match
from etude.eval.run import Tables
from etude.eval.tournament import evaluating
from etude.records import ArtifactRef
import pytest

from manabot.eval import benchmark
from manabot.eval.monitor import MonitorProtocol
from tests.training.test_monitor_evaluation import _manifest

FIXTURE = Path(__file__).parents[1] / "fixtures/etude_sdk_025/benchmark"
RUN = "benchmark-fixture"


def _scheduled() -> tuple[str, list[Match]]:
    manifest = _manifest()
    manifest.protocol = MonitorProtocol(
        deal_seeds=(101, 102), opponent="heuristic", include_mirrors=True
    )
    definition = benchmark.benchmark(manifest)
    checkpoint = CheckpointRef(
        address="migration-fixture/checkpoints/u000050",
        artifact=ArtifactRef(
            uri="file:///fixture/u000050.pt", sha256="2" * 64, size_bytes=10
        ),
    )
    return definition.name, definition.seatings[0].matches(checkpoint)


def _never_play(match: Match) -> Tables:
    pytest.fail(f"retained match was scheduled again: {match.key}")


def _retained_bytes(directory: Path) -> dict[str, bytes]:
    return {
        str(path.relative_to(directory)): path.read_bytes()
        for folder in ("matches", "tables")
        for path in (directory / folder).glob("*")
        if path.is_file()
    }


def test_025_resume_preserves_keys_scores_and_native_seats(tmp_path: Path) -> None:
    experiment, matches = _scheduled()
    store = tmp_path / "store"
    shutil.copytree(FIXTURE, store)
    root = store / RUN
    retained = _retained_bytes(root)
    convert(RUN, store)
    keys = {path.stem for path in (root / "matches").glob("*.json")}
    assert {match.key for match in matches} == keys
    environment = Environment.model_validate_json(
        (root / "environment.json").read_bytes()
    )
    with evaluating(
        environment,
        experiment=experiment,
        run=RUN,
        matches=matches,
        directory=store,
        resume=True,
    ) as active:
        result = active.play(_never_play)
    assert result.played == 0
    assert result.skipped == len(keys)
    assert _retained_bytes(root) == retained
    with statsdb(experiment, store) as db:
        # Opposite native assignments must still join to the same participant.
        grouped = db.execute(
            "select p.name, g.seat, case when g.on_play then 0 else 1 end as game_seat,"
            " count(*), avg(g.score) from plays g"
            " join seats s using (run, match, seat)"
            " join players p on p.player = s.player group by all"
        ).fetchall()
        assert sum(count for _, _, _, count, _ in grouped) == 2 * sum(
            m.games for m in matches
        )
        assert {game_seat for _, _, game_seat, _, _ in grouped} == {0, 1}
        for name, seat, _, count, score in grouped:
            assert count > 0
            assert score == float(1 - seat)
            assert name in {match.players[seat].name for match in matches}
